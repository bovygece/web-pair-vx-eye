/**
 * Random text selector
 * Returns one random message from the provided array.
 */
export function pickRandom(arr) {
  if (!Array.isArray(arr) || arr.length === 0) {
    return "";
  }

  const index = crypto.randomInt(0, arr.length);
  return arr[index];
}
