  "🕊️ বৃদ্ধ বাবা ছেলের পুরোনো স্কুলব্যাগটি যত্ন করে রেখে দিয়েছিলেন। ছেলে হাসত, ‘এটা ফেলে দাও।’ বাবা বলতেন, ‘তোর ছোটবেলার গন্ধ আছে এতে।’ একদিন বাবা আর নেই। ছেলে ব্যাগটি খুলে দেখল ভেতরে তার শৈশবের সব ছোট্ট ছবি।",
