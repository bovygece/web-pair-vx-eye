  "💌 দুজনের পরিচয় হয়েছিল বৃষ্টির দিনে। একজন ছাতা ধরেছিল, অন্যজন বলেছিল, ‘আপনি ভিজে যাচ্ছেন।’ সেই ছোট্ট বাক্য থেকেই প্রতিদিনের অপেক্ষা শুরু হলো। কয়েক বছর পর একই বৃষ্টিতে তারা পাশাপাশি হাঁটল—এইবার ছাতাটা ছিল দুজনেরই।",
  "🌙 নীহারিকা আর রায়ান একই ছাদে দাঁড়িয়ে চাঁদ দেখত। তারা বলত, দূরত্ব যতই হোক, একই আকাশ তো আছে। একদিন রায়ান শহর ছেড়ে চলে গেল। যাওয়ার আগে বলল, ‘চাঁদটা দেখলে আমাকে মনে কোরো।’ নীহারিকা হাসল, ‘তোমাকে মনে করার জন্য চাঁদ লাগবে না।’",
